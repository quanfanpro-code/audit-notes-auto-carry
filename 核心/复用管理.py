# coding: utf-8
"""复用记录管理：本机停用、冲突裁决与影响查询（无 GUI，仅供本机调用）。

所有写入都走共用记录簿的同一把跨进程锁；事件带请求标识，同一请求重试返回同次结果，
同标识不同内容拒绝。影响清单按来源与使用关系分直接、间接两级，任务失踪也保留记录。
"""
from __future__ import annotations

from .共用记录簿 import 记录簿


class 拒绝(ValueError):
    """输入不满足条件，未登记任何事件。"""


def _快照(簿: 记录簿):
    索引 = 簿.快照()
    if not 索引.get("可用"):
        raise RuntimeError("识别记录簿不可用：" + str(索引.get("原因") or "原因不明"))
    return 索引


def _事件内容(事件: dict) -> dict:
    # 失效清单是按当时索引算出来的结果，不属于请求内容，不参与幂等比较
    return {k: v for k, v in 事件.items() if k not in ("结果", "失效")}


def _查请求(簿, 请求标识):
    索引 = _快照(簿)
    已有 = (索引.get("请求") or {}).get(请求标识)
    if not 已有:
        return None
    return 已有.get("事件") or {}


def _影响(索引, 起点: list) -> dict:
    """沿来源与使用关系找受影响任务：直接＝用过的与来源；间接＝依赖链上的任务。"""
    解释 = 索引.get("解释") or {}
    使用 = 索引.get("使用") or []
    依赖 = 索引.get("依赖") or {}
    直接版本 = set(起点)
    影响版本 = set(起点)
    变了 = True
    while 变了:
        变了 = False
        for 版本, 上游 in 依赖.items():
            if 版本 in 影响版本:
                continue
            if set(上游 or []) & 影响版本:
                影响版本.add(版本)
                变了 = True

    def 归集(版本们):
        任务, 表 = set(), set()
        for 版本 in 版本们:
            项 = 解释.get(版本) or {}
            for 来源 in 项.get("来源") or []:
                if 来源.get("任务"):
                    任务.add(str(来源["任务"]))
                    表.add((str(来源.get("侧") or ""), str(来源.get("表组") or "")))
            for 用 in 使用:
                if 用.get("解释版本") != 版本:
                    continue
                if 用.get("任务"):
                    任务.add(str(用["任务"]))
                if 用.get("侧") or 用.get("表组"):
                    表.add((str(用.get("侧") or ""), str(用.get("表组") or "")))
        表.discard(("", ""))
        return {"任务": sorted(任务), "表": [{"侧": 侧, "表组": 组} for 侧, 组 in sorted(表)]}

    直接 = 归集(直接版本)
    全部 = 归集(影响版本)
    间接任务 = sorted(set(全部["任务"]) - set(直接["任务"]))
    间接表 = [x for x in 全部["表"] if x not in 直接["表"]]
    return {"直接": {"任务": 直接["任务"], "表": 直接["表"]},
            "间接": {"任务": 间接任务, "表": 间接表},
            "受影响版本": sorted(影响版本),
            "待复核": sorted(set(全部["任务"]))}


def 停用(簿: 记录簿, 请求标识: str, 解释版本们, 原因: str, 依据: str) -> dict:
    """停用若干解释版本；返回代次、状态与直接／间接影响清单。"""
    版本们 = [str(v) for v in (解释版本们 or []) if v]
    if not 版本们:
        raise 拒绝("停用必须指定解释版本")
    if not str(原因 or "").strip():
        raise 拒绝("停用必须写明原因")
    if not str(依据 or "").strip():
        raise 拒绝("停用必须给出依据引用")
    事件 = {"类型": "停用", "目标": sorted(set(版本们)), "原因": str(原因).strip(),
          "依据": str(依据).strip(), "请求": 请求标识}
    已有 = _查请求(簿, 请求标识)
    if 已有 is not None:
        if _事件内容(已有) != _事件内容(事件):
            raise 拒绝("同一请求标识对应不同内容，拒绝")
        return dict(已有.get("结果") or {}, 请求=请求标识)
    索引 = _快照(簿)
    缺 = [v for v in 版本们 if v not in (索引.get("解释") or {})]
    if 缺:
        raise 拒绝("解释版本不存在或未入库：" + "、".join(缺))
    影响 = _影响(索引, 版本们)
    事件["失效"] = list(影响["受影响版本"])
    事件["结果"] = {"代次": int(索引.get("代次") or 0) + 1, "状态": "已停用", "目标": 事件["目标"],
                  "直接": 影响["直接"], "间接": 影响["间接"],
                  "受影响版本": 影响["受影响版本"], "待复核": 影响["待复核"]}
    簿.提交([事件], 请求标识)
    return dict(事件["结果"], 请求=请求标识)


def 裁决(簿: 记录簿, 请求标识: str, 证据组: str, 预期冲突版本, 保留=None,
       停用们=None, 原因: str = "", 依据: str = "") -> dict:
    """对同一证据下的冲突解释作一次明确选择：保留一个合格版本，或全部停用。"""
    if not str(证据组 or "").strip():
        raise 拒绝("裁决必须指明证据组")
    if not str(依据 or "").strip():
        raise 拒绝("裁决必须给出依据引用")
    预期 = sorted({str(x) for x in (预期冲突版本 or [])})
    保留 = str(保留) if 保留 else None
    停用们 = sorted({str(x) for x in (停用们 or [])})
    if not 预期:
        raise 拒绝("裁决必须给出预期的冲突版本集合")
    if 保留 is None and not 停用们:
        raise 拒绝("裁决必须选择保留版本，或明确全部停用")
    事件 = {"类型": "裁决", "证据组": str(证据组), "预期": 预期,
          "保留": 保留, "停用": 停用们, "原因": str(原因 or "").strip(),
          "依据": str(依据).strip(), "请求": 请求标识}
    已有 = _查请求(簿, 请求标识)
    if 已有 is not None:
        if _事件内容(已有) != _事件内容(事件):
            raise 拒绝("同一请求标识对应不同内容，拒绝")
        return dict(已有.get("结果") or {}, 请求=请求标识)
    索引 = _快照(簿)
    现行有效 = sorted(v for v in (索引.get("按证据") or {}).get(证据组, [])
                  if (索引["解释"].get(v) or {}).get("状态") == "有效")
    现值 = 现行有效
    if 现值 != 预期:
        raise 拒绝(f"冲突版本集合已变化（当前 {现值}），请重读后再裁决")
    if 保留 and 保留 not in 现行有效:
        raise 拒绝("保留的版本不是该证据组的有效解释")
    if any(v not in 预期 for v in 停用们):
        raise 拒绝("停用的版本不在本次冲突集合里")
    if 保留 and 保留 in 停用们:
        raise 拒绝("同一版本不能既保留又停用")
    目标 = 停用们 or [v for v in 现行有效 if v != 保留]
    影响 = _影响(索引, 目标)
    事件["停用"] = 目标
    事件["结果"] = {"代次": int(索引.get("代次") or 0) + 1,
                  "状态": "已裁决" if 保留 else "全部停用",
                  "证据组": 证据组, "保留": 保留, "停用": 目标,
                  "直接": 影响["直接"], "间接": 影响["间接"],
                  "受影响版本": 影响["受影响版本"], "待复核": 影响["待复核"]}
    簿.提交([事件], 请求标识)
    return dict(事件["结果"], 请求=请求标识)


def 查询(簿: 记录簿, 解释版本=None, 请求标识=None) -> dict:
    """按版本或已提交请求查影响清单；不返回旧任务原文，只给任务标识与表组。"""
    if not 解释版本 and not 请求标识:
        raise 拒绝("查询必须给解释版本或请求标识")
    索引 = _快照(簿)
    if 请求标识:
        已有 = (索引.get("请求") or {}).get(请求标识)
        if not 已有:
            raise 拒绝("没有这个请求标识的登记")
        结果 = dict((已有.get("事件") or {}).get("结果") or {})
        结果.update(代次=索引.get("代次"), 请求=请求标识)
        return 结果
    版本 = str(解释版本)
    项 = (索引.get("解释") or {}).get(版本)
    if not 项:
        raise 拒绝("解释版本不存在")
    影响 = _影响(索引, [版本])
    冲突 = [k for k, v in (索引.get("冲突") or {}).items() if 版本 in
          (索引.get("按证据") or {}).get(k, [])]
    return {"代次": 索引.get("代次"), "版本": 版本, "状态": 项.get("状态"),
            "侧": 项.get("侧"), "步骤": 项.get("步骤"),
            "冲突": bool(冲突), "直接": 影响["直接"], "间接": 影响["间接"],
            "待复核": 影响["待复核"]}
