def _假提取(excel, 带连接, 上下文):
    wb = Workbook(); wb.active.title = "sheet1"; wb.active["A1"] = 100
    wb.save(excel)
    pathlib.Path(带连接).write_text("连接体", encoding="utf-8")
    pathlib.Path(上下文).write_text('{"tables": []}', encoding="utf-8")
    return {"ok": True, "table_count": 1, "warnings": []}


# —— 第 11 项：表尾插空行也认作增行 ——

def _建表(路径, 行们, 区域):
    wb = Workbook(); ws = wb.active; ws.title = "s1"
    for 行, 甲, 乙 in 行们:
        ws[f"A{行}"] = 甲; ws[f"B{行}"] = 乙
    for 名, 范围 in 区域.items():
        wb.defined_names[名] = DefinedName(名, attr_text=范围)
    wb.save(路径)
    return 路径


def test_第11项_表尾插空行要认出增行(tmp_path):
    三行 = [(1, "合计", 10), (2, "甲公司", 20), (3, "乙公司", 30)]
    基 = _建表(tmp_path / "基准.xlsx", 三行, {"TA_001": "s1!$A$1:$B$3"})
    改 = _建表(tmp_path / "改后.xlsx", 三行, {"TA_001": "s1!$A$1:$B$3"})
    wb = load_workbook(改); ws = wb["s1"]
    ws.insert_rows(4)                                  # 表尾插一行，命名区域跟着扩一行
    wb.defined_names["TA_001"] = DefinedName("TA_001", attr_text="s1!$A$1:$B$4")
    wb.save(改)
    assert 生成结构操作(基, 改) == [{"range_name": "TA_001", "axis": "row",
                                 "action": "insert", "index": 3, "count": 1,
                                 "template_index": 2}]


# —— 第 12 项：同一完整配对键重复，整张表停 ——

def test_第12项_完整键重复整表停():
    A = [_记("a!B2", "C-N014-T001-S001", 序号=1, 项位置=2),
         _记("a!C2", "C-N014-T001-S001", 序号=1, 项位置=2),      # 同编号、同序号、同期间
         _记("a!B3", "C-N014-T001-S002", 序号=2, 项位置=3)]
    B = [_记("b!B2", "C-N014-T001-S001", 序号=1, 项位置=2, 原值=220),
         _记("b!B3", "C-N014-T001-S002", 序号=2, 项位置=3, 原值=44)]
    清 = 建立对应(A, B, _构(), _构())
    assert all(x["状态"] == "未对应" and x["原因"] == "同侧重复" for x in 清)
    assert not any(x["状态"] == "对应" for x in 清)       # 正常那一项也不许动
