def _四格(词们):
    编号 = "C-N067-T001-S317"
    列们 = [{"列": "B", "路径": "项目", "角色": "行名列", "期间角色": None}]
    for 字母, 词 in zip("CD", 词们):
        列们.append({"列": 字母, "路径": 词 + "金额", "角色": "数据列", "期间角色": 词})
    行们 = [{"行": 1, "名字": "项目", "角色": "表头"},
            {"行": 2, "名字": "期初余额", "角色": "数据", "期间角色": "期初",
             "期间实际": "2025-12-31", "槽位": {"C": 编号, "D": 编号}},
            {"行": 3, "名字": "期末余额", "角色": "数据", "期间角色": "期末",
             "槽位": {"C": 编号, "D": 编号}}]
    出 = _解析精读(_答(列们, 行们), {编号}, 行范围=[1, 3], 列范围={"B", "C", "D"})
    格们 = 铺格子({"工作表": "sheet1", "科目": "货币资金", "表名": "现金等价物", **出})
    for g in 格们:
        g["期间必填"] = True                  # 真实流程里由金标准决定，C-N067 要求期间
    return 格们


