# —— 第 9 项：同一段被多个字段引用不算多个标题；换年不许串改 ——

def _标题入参():
    记录 = [{"格": "s1!A1", "科目": "固定资产", "表名": "固定资产情况",
             "维度值": {"期间角色": "上期期末", "期间实际": "2023-12-31"}},
            {"格": "s1!B1", "科目": "固定资产", "表名": "固定资产情况",
             "维度值": {"期间角色": "本期期末", "期间实际": "2024-12-31"}}]
    对应 = [{"a格": "s1!A1", "b格": "B1", "状态": "对应", "采用来源日期": "2024-12-31"},
            {"a格": "s1!B1", "b格": "B2", "状态": "对应", "采用来源日期": "2025-12-31"}]
    结构 = [{"科目": "固定资产", "表名": "固定资产情况", "区域": "TA_001"}]
    return 对应, 记录, 结构


def test_第9项_同一段被三个字段引用只算一个标题():
    段 = "截至2024年12月31日固定资产情况"
    上下文 = {"tables": [{"range_name": "TA_001", "title": 段,
                       "preceding_blocks": [{"text": 段}],
                       "unit_text_candidates": [段],
                       "chapter_context": [段]}]}
    对应, 记录, 结构 = _标题入参()
    ups, 失败 = 构造标题更新(对应, 记录, 上下文, 结构)
    assert 失败 == []
    assert ups[0]["text"] == "截至2025年12月31日固定资产情况"
    assert ups[0]["old_text"] == 段


def test_第9项_两个年份依次替换不串改():
    上下文 = {"tables": [{"range_name": "TA_001",
                       "chapter_context": ["项目 2023年12月31日及2024年12月31日"]}]}
    对应, 记录, 结构 = _标题入参()
    ups, 失败 = 构造标题更新(对应, 记录, 上下文, 结构)
    assert 失败 == []
    assert ups[0]["text"] == "项目 2024年12月31日及2025年12月31日"


# —— 第 10 项：升级前的旧任务没有输入指纹，不许直接认领 ——

def test_第10项_旧任务无指纹不许混用新旧输入(tmp_path):
    运行目录 = tmp_path / "旧任务"
    运行目录.mkdir()
    wb = Workbook(); wb.active.title = "sheet1"; wb.active["A1"] = 100
    旧表A = tmp_path / "旧公司表A.xlsx"; wb.save(旧表A)
    上下文 = tmp_path / "上下文.json"
    上下文.write_text('{"tables": []}', encoding="utf-8")
    连接 = tmp_path / "带连接.docx"; 连接.write_text("连接体", encoding="utf-8")
    wb2 = Workbook(); wb2.active.title = "word附注"; wb2.active["A1"] = 9
    新表B = tmp_path / "新公司B.xlsx"; wb2.save(新表B)
    写索引(运行目录, {"步骤": "identify_a", "已完成范围": ["提取"],
                    "产物": {"表A": str(旧表A), "上下文": str(上下文),
                           "带连接Word": str(连接)}})      # 升级前的老任务：没有输入指纹
    try:
        运行任务({"word": "原.docx", "b表": str(新表B),
               "金标准": str(_金标准(tmp_path))}, 运行目录, {})
        assert False, "没有指纹却已产出旧 A，必须拒绝续跑"
    except RuntimeError as e:
        assert "指纹" in str(e) and "新建任务" in str(e)


