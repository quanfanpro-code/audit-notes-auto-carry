# —— 第 3 项：横向名单清尾按序号，不按列字母；清尾要逐项进问题清单 ——

def _记(格, 槽位, 序号=None, 项位置=None, 角色="数据格", 期间="本期期末",
        科目="固定资产", 表名="固定资产情况", 原值=1, 状态="值"):
    行号 = int("".join(ch for ch in 格.split("!")[-1] if ch.isdigit()) or 1)
    return {"格": 格, "科目": 科目, "表名": 表名, "表组": "G1", "行号": 行号,
            "项方式": "列", "项位置": 项位置 or str(行号), "序号": 序号, "角色": 角色,
            "维度值": {"期间角色": 期间, "期间实际": "2025-12-31", "币种": "人民币",
                     "单位": "元", "期间跨度": "时点", "主体": "未知", "报表范围": "合并"},
            "期间必填": True, "槽位": 槽位, "原值": 原值, "原值状态": 状态}


def _构(科目="固定资产", 表名="固定资产情况", 分组=True):
    return [{"科目": 科目, "表名": 表名,
             "完整性": {"第一遍覆盖": 分组, "第二遍归段": 分组,
                      "第三遍逐行": 分组, "空名单已声明": 分组},
             "空名单": []}]


