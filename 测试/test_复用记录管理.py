# coding: utf-8
"""复用记录管理：停用、裁决与影响查询；请求幂等、冲突集合与依据校验。"""
import json
from pathlib import Path

import pytest

from 核心.共用记录簿 import 记录簿, 发布事件, 使用事件
from 核心.复用管理 import 停用, 裁决, 查询, 拒绝


def _发布(簿, 版本, 证据键, 解释键, 任务, 依赖=(), 侧="A", 组="G1"):
    簿.提交([发布事件(侧, "第三遍", {"证据版本": 1}, {"科目": "货币资金"},
                   证据键, 解释键, 版本, "金", "规",
                   {"任务": 任务, "侧": 侧, "表组": 组}, 形状键=None, 依赖=list(依赖))],
            "发布:" + 版本)


def _用(簿, 版本, 任务, 组="G1"):
    簿.提交([使用事件(版本, 任务, "A", 组, 0)], f"使用:{任务}:{版本}")


def _链(tmp_path):
    簿 = 记录簿(tmp_path / "记录")
    _发布(簿, "V甲", "证甲", "解甲", "任务甲")
    _用(簿, "V甲", "任务乙")
    _发布(簿, "V乙", "证乙", "解乙", "任务乙", 依赖=["V甲"])
    _用(簿, "V乙", "任务丙")
    _发布(簿, "V丙", "证丙", "解丙", "任务丙", 依赖=["V乙"])
    return 簿


def test_停用列出直接与间接受影响任务(tmp_path):
    簿 = _链(tmp_path)
    结果 = 停用(簿, "停用甲", ["V甲"], "原表认错科目", "复核记录#12")
    assert 结果["状态"] == "已停用"
    assert set(结果["直接"]["任务"]) == {"任务甲", "任务乙"}      # 来源任务＋使用过它的任务
    assert set(结果["间接"]["任务"]) == {"任务丙"}               # 依赖链上的下游任务
    assert set(结果["待复核"]) == {"任务甲", "任务乙", "任务丙"}
    assert 簿.快照()["解释"]["V甲"]["状态"] == "停用"


def test_重复请求返回同次结果_改内容拒绝(tmp_path):
    簿 = _链(tmp_path)
    一 = 停用(簿, "同一停用", ["V甲"], "错认", "依据A")
    二 = 停用(簿, "同一停用", ["V甲"], "错认", "依据A")
    assert 一 == 二
    assert 簿.快照()["代次"] == 一["代次"]
    with pytest.raises(拒绝, match="不同内容"):
        停用(簿, "同一停用", ["V甲"], "另一个原因", "依据A")


def test_缺依据或目标不存在被拒(tmp_path):
    簿 = _链(tmp_path)
    with pytest.raises(拒绝, match="依据"):
        停用(簿, "无依据", ["V甲"], "错认", "")
    with pytest.raises(拒绝, match="不存在|未入库"):
        停用(簿, "无目标", ["V不存在"], "错认", "依据A")


def test_源文件已移动或中断的任务仍保留在影响清单(tmp_path):
    簿 = _链(tmp_path)
    幽灵 = str(tmp_path / "已删除的任务目录")
    _用(簿, "V甲", 幽灵)
    结果 = 停用(簿, "停用甲", ["V甲"], "错认", "依据")
    assert 幽灵 in 结果["直接"]["任务"]          # 不因目录不存在而消失


def test_冲突裁决保留合格版本并解除阻止(tmp_path):
    簿 = 记录簿(tmp_path / "记录")
    _发布(簿, "V1", "证同", "解一", "任务甲")
    _发布(簿, "V2", "证同", "解二", "任务乙")
    索引 = 簿.快照()
    assert 索引["冲突"].get("证同") == ["V1", "V2"]
    with pytest.raises(拒绝, match="冲突版本集合已变化"):
        裁决(簿, "裁决过期", "证同", ["V1"], 保留="V1", 依据="复核")
    结果 = 裁决(簿, "裁决一", "证同", ["V1", "V2"], 保留="V1", 原因="V2 把存货认成固定资产",
             依据="复核#7")
    assert 结果["状态"] == "已裁决" and 结果["保留"] == "V1"
    后 = 簿.快照()
    assert 后["解释"]["V2"]["状态"] == "停用"
    assert not 后["冲突"]                        # 有明确裁决后不再阻止
    assert 查询(簿, 解释版本="V1")["冲突"] is False


def test_裁决全部停用与非法输入(tmp_path):
    簿 = 记录簿(tmp_path / "记录")
    _发布(簿, "V1", "证同", "解一", "任务甲")
    _发布(簿, "V2", "证同", "解二", "任务乙")
    with pytest.raises(拒绝, match="不在本次冲突集合"):
        裁决(簿, "越界", "证同", ["V1", "V2"], 保留="V2", 停用们=["V3"], 依据="x")
    with pytest.raises(拒绝, match="既保留又停用"):
        裁决(簿, "自相矛盾", "证同", ["V1", "V2"], 保留="V1", 停用们=["V1"], 依据="x")
    结果 = 裁决(簿, "全停", "证同", ["V1", "V2"], 停用们=["V1", "V2"], 依据="两边都错")
    assert 结果["状态"] == "全部停用"
    assert 簿.快照()["解释"]["V1"]["状态"] == "停用"


def test_按请求标识查询返回当次登记结果(tmp_path):
    簿 = _链(tmp_path)
    结果 = 停用(簿, "停用甲", ["V甲"], "错认", "依据")
    查 = 查询(簿, 请求标识="停用甲")
    assert 查["直接"] == 结果["直接"] and 查["间接"] == 结果["间接"]
    with pytest.raises(拒绝, match="没有这个请求"):
        查询(簿, 请求标识="不存在的请求")
    # 返回内容不含旧任务原文，只有任务标识与表组
    文 = json.dumps(查, ensure_ascii=False)
    assert "原文" not in 文 and "标题" not in 文
