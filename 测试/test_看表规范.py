# coding: utf-8
"""看表规范：三段模板必须内嵌、够完整、逐段递进。"""
from 核心 import 看表规范


def test_三段都存在且不短():
    for 名 in ("分科目规范", "分表规范", "精读规范"):
        文本 = getattr(看表规范, 名)()
        assert len(文本) > 800, f"{名} 太短，说明裁剪时删过头了"




def test_精读规范覆盖关键规则():
    文本 = 看表规范.精读规范()
    for 关键词 in ("列表头", "行表头", "跨", "作用范围", "停止强猜", "例外"):
        assert 关键词 in 文本, f"精读规范缺 {关键词}"




def test_三段递进():
    assert len(看表规范.分表规范()) > len(看表规范.分科目规范())
    assert len(看表规范.精读规范()) > len(看表规范.分表规范())




def test_每段都写明分工边界():
    for 名 in ("分科目规范", "分表规范", "精读规范"):
        文本 = getattr(看表规范, 名)()
        assert "不要输出任何数值" in 文本, f"{名} 缺分工边界"
        assert "不要改原文" in 文本, f"{名} 缺分工边界"
