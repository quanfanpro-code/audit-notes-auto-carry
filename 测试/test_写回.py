# coding: utf-8
"""写回只执行给定的标题更新：没给就不动，给了就照搬原文与新文。"""
import pytest

from 核心.写回 import 读标题更新


def test_没给标题就不改():
    assert 读标题更新([]) == []
    assert 读标题更新([{"区域": "TA_008", "科目": "货币资金", "表名": "余额构成"}]) == []


def test_给了标题就照搬原文与新文():
    出 = 读标题更新([{"区域": "TA_008", "科目": "货币资金", "表名": "余额构成",
                  "标题": {"原文": "期末指2024年12月31日",
                         "新文": "期末指2025年12月31日"}}])
    assert 出 == [{"range_name": "TA_008",
                 "old_text": "期末指2024年12月31日",
                 "text": "期末指2025年12月31日"}]


def test_只给一半就报错():
    for 坏 in ({"原文": "甲", "新文": ""}, {"原文": "", "新文": "乙"}):
        with pytest.raises(RuntimeError):
            读标题更新([{"区域": "TA_008", "标题": 坏}])
