def test_上下文段落是列表也能定位():
    """真实提取的 chapter_context 是段落列表，不能整串 str() 带出方括号。"""
    上下文 = {"tables": [{"range_name": "TA_001",
                       "chapter_context": ["截至2024年12月31日固定资产情况", "单位：人民币元"]}]}
    A记录 = {"格": "s1!A1", "科目": "固定资产", "表名": "固定资产情况",
             "维度值": {"期间角色": "本期期末", "期间实际": "2024-12-31"}}
    对应 = [{"a格": "s1!A1", "b格": "B1", "状态": "对应", "采用来源日期": "2025-12-31"}]
    结构 = [{"科目": "固定资产", "表名": "固定资产情况", "区域": "TA_001"}]
    ups, 失败 = 构造标题更新(对应, [A记录], 上下文, 结构)
    assert 失败 == []
    assert ups[0]["old_text"] == "截至2024年12月31日固定资产情况"   # 原句干净，没有方括号
    assert ups[0]["text"] == "截至2025年12月31日固定资产情况"


