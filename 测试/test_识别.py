def test_三遍串行且合集原值来自文件(tmp_path, monkeypatch):
    顺序 = []

    def 假调用(配置, 指令, 材料, 调用目录):
        if 指令.startswith("把整份文件"):
            顺序.append("一")
            return '{"划分":[{"行范围":[1,2],"科目":"货币资金"}]}'
        if 指令.startswith("在第一遍"):
            顺序.append("二")
            return '{"表":[{"行范围":[1,2],"科目":"货币资金","表名":"余额构成"}]}'
        顺序.append("三")
        return ('{"列":[{"列":"B","路径":"项目","角色":"行名列","期间":null},'
                '{"列":"C","路径":"期末余额","角色":"数据列","期间":"期末"}],'
                '"行":[{"行":1,"名字":"项目","角色":"表头"},'
                '{"行":2,"名字":"库存现金","角色":"数据","槽位":{"C":"C-N006-T001-S002"}}],'
                '"作用范围":{"币种":"人民币","单位":"元"},"例外":[]}')

    monkeypatch.setattr("核心.识别.调用识别", 假调用)
    wb = Workbook(); ws = wb.active; ws.title = "s1"
    ws["A1"] = "行\\列"; ws["B1"] = "项目"; ws["C1"] = "期末余额"
    ws["B2"] = "库存现金"; ws["C2"] = 12987.5
    p = tmp_path / "A.xlsx"; wb.save(p)
    配置 = {"url": "u", "api_key": "k", "model": "m", "timeout": 1}
    结果 = 识别一侧(配置, str(p), "A", tmp_path / "任务", _造金标准(tmp_path))
    assert 顺序 == ["一", "二", "三"]                 # 三遍串行，不许换序
    assert 结果["待答复"] == []
    记录 = [json.loads(x) for x in 结果["合集"].read_text(encoding="utf-8").splitlines()]
    assert [r["格"] for r in 记录] == ["s1!C2"]
    assert 记录[0]["原值"] == 12987.5
    assert 记录[0]["槽位"] == "C-N006-T001-S002"
    assert 记录[0]["槽位名"] == "库存现金 / 期末余额"   # 名字取自金标准，不由模型写



