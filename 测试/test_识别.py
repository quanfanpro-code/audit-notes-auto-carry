def test_补原值只认文件不认答复(tmp_path):
    wb = Workbook(); ws = wb.active; ws.title = "s1"; ws["A1"] = 100
    p = tmp_path / "a.xlsx"; wb.save(p)
    快照 = 读快照(p)
    出 = 补原值([{"格": "s1!A1", "原值": "模型瞎写", "原值状态": "值"},
              {"格": "s1!B9", "原值": 999, "原值状态": "值"}], 快照)
    assert 出[0]["原值"] == 100 and 出[0]["原值状态"] == "值"     # 文件说话，模型的值被丢掉
    assert 出[1]["原值"] is None and 出[1]["原值状态"] == "读取失败"


def _造金标准(tmp_path):
    路径 = tmp_path / "金标准.jsonl"
    行 = {"note": {"name": "货币资金", "display_order": 1},
          "table": {"name": "余额构成", "display_order": 1},
          "slot": {"name": "库存现金 / 期末余额"}, "id": "C-N006-T001-S002",
          "row_path": ["库存现金"], "column_path": ["期末余额"]}
    路径.write_text(json.dumps(行, ensure_ascii=False) + "\n", encoding="utf-8")
    return 路径


