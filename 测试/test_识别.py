def _精读答复(行们, 列们=None, 空名单=None, 作用范围=None):
    return json.dumps({
        "列": 列们 or [{"列": "B", "路径": "项目", "角色": "行名列", "期间角色": None},
                     {"列": "C", "路径": "期末余额", "角色": "数据列", "期间角色": "本期期末"}],
        "行": 行们,
        "作用范围": 作用范围 or {"币种": "人民币", "单位": "元"},
        "空名单": 空名单 or [],
        "例外": [],
    }, ensure_ascii=False)


def _行(行号, 名字="库存现金", 角色="数据", 序号=None, 槽位=None, 不搬原因=None):
    r = {"行": 行号, "名字": 名字, "角色": 角色, "序号": 序号,
         "槽位": {"C": "C-N087-T001-S001"} if 槽位 is None else 槽位}
    if 不搬原因:
        r["不搬原因"] = 不搬原因
    return r


