def test_没答复完的表不算漏行():
    """中途跑：还没交的表不该报漏行，否则问题清单全是噪声。"""
    from 核心.识别 import _完整性

    快照 = _快照([(2, "甲"), (3, "乙"), (4, "丙")])
    本侧 = [
        {"区域": "T1", "工作表": "sheet1", "范围": "$B$2:$B$3", "行范围": [2, 3],
         "科目": "货币资金", "表名": "余额构成", "完成": True,
         "行": [{"行": 2}, {"行": 3}], "列": [{"列": "B"}]},
        {"区域": "T2", "工作表": "sheet1", "范围": "$B$4:$B$5", "行范围": [4, 5],
         "科目": "货币资金", "表名": "明细", "完成": False, "行": [], "列": [],
         "漏行": [4, 5]},                      # 上一轮留下的旧值
    ]
    划分 = [{"行范围": [1, 5], "科目": "货币资金"}]
    r = _完整性(划分, 本侧, 快照)
    assert r["漏行"] == {}                     # 未完成的表不报
    assert 本侧[1].get("漏行") is None          # 旧值要清掉，不能留
    assert r["第三遍逐行"] is False             # 但整表还没做完，仍不算完整


