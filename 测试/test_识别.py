def test_铺格子按行列交叉并跳过表头与行名列():
    结构 = {
        "侧": "A", "区域": "TA_008", "行范围": [56, 60],
        "科目": "货币资金", "表名": "余额构成",
        "列": [{"列": "B", "路径": "项目", "角色": "行名列", "期间": None},
              {"列": "C", "路径": "期末余额", "角色": "数据列", "期间": "期末"},
              {"列": "D", "路径": "期初余额/账面余额", "角色": "数据列", "期间": "期初"}],
        "行": [{"行": 56, "名字": "项目", "角色": "表头"},
              {"行": 57, "名字": "库存现金", "角色": "数据",
               "槽位": {"C": "C-N006-T001-S002", "D": "C-N006-T001-S003"}},
              {"行": 58, "名字": "银行存款", "角色": "数据",
               "槽位": {"C": "C-N006-T001-S004", "D": "C-N006-T001-S005"}}],
        "作用范围": {"币种": "人民币", "单位": "元"},
        "例外": [],
    }
    格们 = 铺格子(结构)
    坐标 = [g["格"] for g in 格们]
    assert 坐标 == ["sheet1!C57", "sheet1!D57", "sheet1!C58", "sheet1!D58"]   # 表头行不出、B列不参与
    首 = 格们[0]
    assert 首["行路径"] == ["库存现金"] and 首["列路径"] == ["期末余额"]
    assert 首["维度值"]["期间角色"] == "期末" and 首["维度值"]["币种"] == "人民币"
    assert 首["槽位"] == "C-N006-T001-S002"
    assert 格们[1]["列路径"] == ["期初余额", "账面余额"]   # 多级列路径按层拆开，不拍平


