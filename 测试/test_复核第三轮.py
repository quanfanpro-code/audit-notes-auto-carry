# —— 第 1 项：横向名单漏交一列，仍被当成完整 ——

def _横向表(path, 列名们):
    wb = Workbook(); ws = wb.active; ws.title = "s1"
    ws["B1"] = "项目（单位：人民币元）"
    for 字母, 名 in zip("CDE", 列名们):
        ws[f"{字母}1"] = 名
    ws["B2"] = "期末余额"
    for 字母, 值 in zip("CDE", (110, 220, 330)):
        ws[f"{字母}2"] = 值
    wb.save(path)
    return path


