def _两项(第二项不搬=False, 第二项重复=False):
    列们 = [{"列": "B", "路径": "项目", "角色": "行名列", "期间角色": None},
            {"列": "C", "路径": "余额", "角色": "数据列", "期间角色": "本期期末"}]
