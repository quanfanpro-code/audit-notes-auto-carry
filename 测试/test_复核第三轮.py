# —— 第 4 项：表尾插空行同时改金额 ——

def _建表(path, 行们, 区域):
    wb = Workbook(); ws = wb.active; ws.title = "s1"
    for 行, 甲, 乙 in 行们:
        ws[f"A{行}"] = 甲; ws[f"B{行}"] = 乙
    for 名, 范围 in 区域.items():
        wb.defined_names[名] = DefinedName(名, attr_text=范围)
    wb.save(path)
    return path
