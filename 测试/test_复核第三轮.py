def _金标准(tmp_path, 编号们=(编号,)):
    路径 = tmp_path / "金标准.jsonl"
    行们 = []
    for 号 in 编号们:
        行们.append(json.dumps({
            "note": {"name": "固定资产", "display_order": 1},
            "table": {"name": "固定资产情况", "display_order": 1},
            "slot": {"name": "账面原值 / 期末余额"}, "id": 号,
            "row_path": ["账面原值"], "column_path": ["<资产类别>"],
            "dimensions": [{"name": "period", "required": True}]}, ensure_ascii=False))
    路径.write_text("\n".join(行们) + "\n", encoding="utf-8")
    return 路径


def _答(列们, 行们, 空名单=None, 例外=None):
    return json.dumps({"列": 列们, "行": 行们, "作用范围": 单位作用("B1", "项目（单位：人民币元）", [c["列"] for c in 列们 if c["角色"] == "数据列"]), "空名单": 空名单 or [],
                       "例外": 例外 or []}, ensure_ascii=False)


