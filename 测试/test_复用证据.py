    for i, (名, 期初, 期末) in enumerate([("甲公司", 1, 2), ("乙公司", 3, 4), ("合计", 4, 6)], 2):
        ws.cell(i, 1, 名)
        ws.cell(i, 2, 期末)          # 故意对调
        ws.cell(i, 3, 期初)
    p2 = tmp_path / "对调.xlsx"
    wb.save(p2)
    wb.close()
    出 = 核对精读(证据, 表视图(读快照(p2), "sheet1", (1, 1, 4, 4)))
    assert 出["结果"] == "未命中"
    assert "固定文字" in 出["原因"] or "日期" in 出["原因"]


