def _表(tmp_path, 名, 行们, 首行=("项目", "期初余额", "期末余额", "单位：元")):
    wb = Workbook()
    ws = wb.active
    ws.title = "sheet1"
    for c, 文 in enumerate(首行, 1):
        ws.cell(1, c, 文)
    for i, (名2, 期初, 期末) in enumerate(行们, 2):
        ws.cell(i, 1, 名2)
        ws.cell(i, 2, 期初)
        ws.cell(i, 3, 期末)
    p = tmp_path / f"{名}.xlsx"
    wb.save(p)
    wb.close()
    return p


def _记录(行数=4, 科目="货币资金", 表名="余额构成", 组="G1", 续表序=1, 起=1):
    行们 = [{"行": 起, "名字": "项目", "角色": "表头"}]
    for i in range(2, 行数 + 1):
        角色 = "合计" if i == 行数 else "数据"
        行们.append({"行": 起 + i - 1, "名字": "甲公司" if i == 2 else ("乙公司" if i == 3 else "合计"),
                   "角色": 角色, "序号": None if 角色 == "合计" else i - 1,
                   "槽位": {"B": "C-N006-T001-S002", "C": "C-N006-T001-S003"}})
    return {"侧": "A", "工作表": "sheet1", "区域": "TA_001",
            "范围": f"A{起}:D{起 + 行数 - 1}", "行范围": [起, 起 + 行数 - 1],
            "科目": 科目, "表名": 表名, "表组": 组, "续表序": 续表序,
            "列": [{"列": "A", "路径": "项目", "角色": "行名列", "期间角色": None},
                  {"列": "B", "路径": "期初余额", "角色": "数据列", "期间角色": "本期期初",
                   "期间实际": "2025-01-01", "期间实际位置": f"B{起}"},
                  {"列": "C", "路径": "期末余额", "角色": "数据列", "期间角色": "本期期末",
                   "期间实际": "2025-12-31", "期间实际位置": f"C{起}"},
                  {"列": "D", "路径": "单位", "角色": "说明列", "期间角色": None}],
            "行": 行们, "作用范围": {"币种": "人民币", "单位": "元"},
            "空名单": [], "例外": [], "完成": True}


def _证据(tmp_path, 名, 行们, **设置):
    p = _表(tmp_path, 名, 行们)
    快照 = 读快照(p)
    记录 = _记录(**设置)
    证据 = 建证据_精读("A", [记录], 快照)
    return 证据, 快照, 记录


def test_金额与名单名称变化仍相符(tmp_path):
    证据, 快照, _ = _证据(tmp_path, "上年", [("甲公司", 100, 110), ("乙公司", 200, 210),
                                          ("合计", 300, 320)])
    新 = _表(tmp_path, "本年", [("丙公司", 999, 888), ("丁公司", 1, 2), ("合计", 1000, 890)],
            首行=("项目", "2026年1月1日", "2026年12月31日", "单位：元"))
    新视图 = 表视图(读快照(新), "sheet1", (1, 1, 4, 4))
    # 上年表头写的是日期文字，本年换年：日期位置只要求仍是日期
    出 = 核对精读(证据, 新视图)
    assert 出["结果"] == "唯一", 出
    解释 = 出["解释"]
    assert [c["列"] for c in 解释["列"]] == ["A", "B", "C", "D"]
    assert [r["行"] for r in 解释["行"]] == [1, 2, 3, 4]
    assert 解释["行"][1]["槽位"] == {"B": "C-N006-T001-S002", "C": "C-N006-T001-S003"}


def test_同一证据下金额不同不改变证据键(tmp_path):
    甲, _, _ = _证据(tmp_path, "甲", [("甲公司", 100, 110), ("乙公司", 200, 210), ("合计", 300, 320)])
    乙, _, _ = _证据(tmp_path, "乙", [("甲公司", 1, 2), ("乙公司", 3, 4), ("合计", 4, 6)])
    assert 证据键(甲) == 证据键(乙)
    # 旧证据里不得留下金额
    文 = json.dumps(甲, ensure_ascii=False)
    for 数 in ("100", "110", "200", "210"):
        assert f'"{数}"' not in 文


