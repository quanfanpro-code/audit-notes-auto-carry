def test_同证据不同槽位解释键不同(tmp_path):
    证据, 快照, 记录 = _证据(tmp_path, "甲", [("甲公司", 100, 110), ("乙公司", 200, 210), ("合计", 300, 320)])
    改 = json.loads(json.dumps(记录, ensure_ascii=False))
    改["行"][1]["槽位"] = {"B": "C-N006-T001-S002", "C": "C-N006-T001-S009"}
    另 = 建证据_精读("A", [改], 快照)
    assert 证据键(证据) == 证据键(另)          # 结构与固定原文一样
    assert 解释键(证据["解释"]) != 解释键(另["解释"])
    assert 版本号(证据键(证据), 解释键(证据["解释"]), "金甲", "规甲") != \
        版本号(证据键(另), 解释键(另["解释"]), "金甲", "规甲")


