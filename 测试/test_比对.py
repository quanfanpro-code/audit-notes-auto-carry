# coding: utf-8
"""比对引擎测试：按金标准槽位编号配对，写法差异不影响。"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from 核心.比对 import 建立对应


def 记(格, 槽位="C-N001-T001-S001", 原值=1):
    return {"格": 格, "科目": "货币资金", "表名": "余额构成",
            "行路径": ["库存现金"], "列路径": ["期末余额"],
            "槽位": 槽位, "槽位名": "库存现金 / 期末余额",
            "维度值": {"期间角色": "期末", "期间实际": "2025-12-31", "选取范围": "库存现金",
                      "币种": "人民币", "主体": "未知", "报表范围": "未知", "单位": "元"},
            "原值": 原值, "原值状态": "值"}


def test_同编号就对应_金额不同也连():
    清单 = 建立对应([记("A1", 原值=100)], [记("B1", 原值=200)])
    对 = [x for x in 清单 if x["状态"] == "对应"]
    assert len(对) == 1 and 对[0]["a格"] == "A1" and 对[0]["b格"] == "B1"


def test_编号不同就不连():
    清单 = 建立对应([记("A1", "C-N001-T001-S001")], [记("B1", "C-N001-T001-S002")])
    原因 = sorted(x["原因"] for x in 清单)
    assert 原因 == ["仅A侧有", "仅B侧有"]


def test_重复与缺失():
    清单 = 建立对应([记("A1"), 记("A2")], [记("B1")])
    assert all(x["原因"] == "A侧重复" for x in 清单)
    清单 = 建立对应([记("A1", "")], [记("B1", "")])
    assert all(x["原因"] == "槽位编号缺失" for x in 清单)
    assert len(清单) == 2                     # 未对应的也要逐条在清单里，不丢


def test_写法差异不影响_因为比的是编号():
    # 两侧槽位名写法完全不同，但编号相同 → 必须对上
    a = 记("A1"); a["槽位名"] = "预付款项-账龄 / 1年以内（含1年）/ 期末余额"
    b = 记("B1"); b["槽位名"] = "预付款项按账龄列示 / 1年以内 / 期末余额"
    assert 建立对应([a], [b])[0]["状态"] == "对应"


def test_采用来源日期取自B侧():
    清单 = 建立对应([记("A1")], [记("B1")])
    assert 清单[0]["采用来源日期"] == "2025-12-31"

