"""比对引擎测试：按金标准槽位编号配对，写法差异不影响。"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from 核心.比对 import 建立对应


def 记(格, 槽位="C-N001-T001-S001", 原值=1):
    return {"格": 格, "科目": "货币资金", "表名": "余额构成",
            "行路径": ["库存现金"], "列路径": ["期末余额"],
            "槽位": 槽位, "槽位名": "库存现金 / 期末余额",
            "维度值": {"期间角色": "期末", "期间实际": "2025-12-31", "选取范围": "库存现金",
                      "币种": "人民币", "主体": "未知", "报表范围": "未知", "单位": "元"},
            "原值": 原值, "原值状态": "值"}


def test_同编号就对应_金额不同也连():
    清单 = 建立对应([记("A1", 原值=100)], [记("B1", 原值=200)])
    对 = [x for x in 清单 if x["状态"] == "对应"]
    assert len(对) == 1 and 对[0]["a格"] == "A1" and 对[0]["b格"] == "B1"


def test_编号不同就不连():
    清单 = 建立对应([记("A1", "C-N001-T001-S001")], [记("B1", "C-N001-T001-S002")])
    原因 = sorted(x["原因"] for x in 清单)
    assert 原因 == ["仅A侧有", "仅B侧有"]


def test_重复与缺失():
    清单 = 建立对应([记("A1"), 记("A2")], [记("B1")])
    assert all(x["原因"] == "同侧重复" for x in 清单)   # 术语统一为同侧重复
    清单 = 建立对应([记("A1", "")], [记("B1", "")])
    assert all(x["原因"] == "槽位编号缺失" for x in 清单)
    assert len(清单) == 2                     # 未对应的也要逐条在清单里，不丢


def test_写法差异不影响_因为比的是编号():
    # 两侧槽位名写法完全不同，但编号相同 → 必须对上
    a = 记("A1"); a["槽位名"] = "预付款项-账龄 / 1年以内（含1年）/ 期末余额"
    b = 记("B1"); b["槽位名"] = "预付款项按账龄列示 / 1年以内 / 期末余额"
    assert 建立对应([a], [b])[0]["状态"] == "对应"


def test_采用来源日期取自B侧():
    清单 = 建立对应([记("A1")], [记("B1")])
    assert 清单[0]["采用来源日期"] == "2025-12-31"


# —— R4：按编号（＋序号）（＋期间角色）配对、清尾、口径、项数 ——

组 = ("货币资金", "余额构成")


def _记(格, 槽, 组=组, 表组=None, 序号=None, 角色="数据格", 期间="本期期末",
        必填=True, 行号=None, 币种="人民币", 单位="元", 跨度="时点", 分组=None, 原值=1):
    if 行号 is None:
        行号 = int("".join(ch for ch in 格.split("!")[1] if ch.isdigit()) or 1)
    return {"格": 格, "科目": 组[0], "表名": 组[1],
            "表组": 表组 or (组[0] + "|" + 组[1]), "行号": 行号,
            "序号": 序号, "角色": 角色, "分组": 分组,
            "维度值": {"期间角色": 期间, "期间实际": "2025-12-31", "币种": 币种,
                     "单位": 单位, "期间跨度": 跨度, "主体": "未知", "报表范围": "合并"},
            "期间必填": 必填, "槽位": 槽, "原值": 原值, "原值状态": "值"}


def _构(组=组, 完整=True, 空名单=None):
    return [{"科目": 组[0], "表名": 组[1],
             "完整性": {"第一遍覆盖": 完整, "第二遍归段": 完整,
                      "第三遍逐行": 完整, "空名单已声明": 完整},
             "空名单": 空名单 or []}]


def test_固定编号顺序相反仍对应():
    A = [_记("a!B2", "S-库存现金", 行号=2), _记("a!B3", "S-银行存款", 行号=3)]
    B = [_记("b!B2", "S-银行存款", 行号=2), _记("b!B3", "S-库存现金", 行号=3)]
    清 = 建立对应(A, B, _构(), _构())
    assert [x["状态"] for x in 清 if x["a格"]] == ["对应", "对应"]


def test_名单按序号配():
    A = [_记("a!B2", "S1", 序号=1, 行号=2), _记("a!B3", "S1", 序号=2, 行号=3)]
    B = [_记("b!B2", "S1", 序号=1, 行号=2), _记("b!B3", "S1", 序号=2, 行号=3)]
    清 = {x["a格"]: x["b格"] for x in 建立对应(A, B, _构(), _构())}
    assert 清["a!B2"] == "b!B2" and 清["a!B3"] == "b!B3"


def test_期间角色不同不配():
    A = [_记("a!B2", "S1", 期间="本期期初", 行号=2)]
    B = [_记("b!B2", "S1", 期间="本期期末", 行号=2)]
    清 = 建立对应(A, B, _构(), _构())
    assert all(x["状态"] == "未对应" for x in 清)


def test_两个未知不得配成一对():
    A = [_记("a!B2", "S1", 期间="未知", 行号=2)]
    B = [_记("b!B2", "S1", 期间="未知", 行号=2)]
    x = [r for r in 建立对应(A, B, _构(), _构()) if r["a格"]][0]
    assert x["状态"] == "未对应" and x["原因"] == "期间角色未知"


def test_不需期间的编号期间不同也照配():
    A = [_记("a!B2", "S-款项性质", 期间="本期期末", 必填=False, 行号=2)]
    B = [_记("b!B2", "S-款项性质", 期间="未知", 必填=False, 行号=2)]
    x = [r for r in 建立对应(A, B, _构(), _构()) if r["a格"]][0]
    assert x["状态"] == "对应" and x["b格"] == "b!B2"


def test_不需期间的编号判重不看期间():
    A = [_记("a!B2", "S-款项性质", 期间="本期期末", 必填=False, 行号=2),
         _记("a!B3", "S-款项性质", 期间="本期期初", 必填=False, 行号=3)]
    B = [_记("b!B2", "S-款项性质", 期间="未知", 必填=False, 行号=2)]
    清 = [r for r in 建立对应(A, B, _构(), _构()) if r["a格"]]
    assert all(x["状态"] == "未对应" and x["原因"] == "同侧重复" for x in 清)


def test_A缺编号不判加项且不配错():
    A = [_记("a!B2", "", 行号=2), _记("a!B3", "S1", 行号=3)]
    B = [_记("b!B2", "S2", 行号=2), _记("b!B3", "S1", 行号=3)]
    清 = 建立对应(A, B, _构(), _构())
    原因们 = {x["原因"] for x in 清}
    assert "需加项" not in 原因们                       # 行数一样，不许误判加项
    a2 = [x for x in 清 if x["a格"] == "a!B2"][0]
    assert a2["原因"] == "槽位编号缺失"
    a3 = [x for x in 清 if x["a格"] == "a!B3"][0]
    assert a3["状态"] == "对应" and a3["b格"] == "b!B3"   # 不许配到 b!B2


def test_完整性不足不清尾():
    A = [_记("a!B2", "S1", 序号=1, 行号=2), _记("a!B3", "S1", 序号=2, 行号=3)]
    B = [_记("b!B2", "S1", 序号=1, 行号=2)]
    坏 = [r for r in 建立对应(A, B, _构(), _构(完整=False)) if r["a格"] == "a!B3"][0]
    assert 坏["状态"] == "未对应" and 坏["原因"] == "仅A侧有"
    好 = [r for r in 建立对应(A, B, _构(), _构()) if r["a格"] == "a!B3"][0]
    assert 好["状态"] == "清尾"


def test_B多于A整表停():
    A = [_记("a!B2", "S1", 行号=2), _记("a!B3", "S2", 行号=3)]
    B = [_记("b!B2", "S1", 行号=2), _记("b!B3", "S2", 行号=3), _记("b!B4", "S3", 行号=4)]
    清 = 建立对应(A, B, _构(), _构())
    assert all(x["状态"] == "未对应" for x in 清)
    assert all(x["原因"] == "需加项" for x in 清)


def test_币种或单位冲突整表停():
    A = [_记("a!B2", "S1", 币种="人民币", 单位="元")]
    B = [_记("b!B2", "S1", 币种="美元", 单位="元")]
    assert all(x["原因"] == "口径冲突" for x in 建立对应(A, B, _构(), _构()))
    A2 = [_记("a!B2", "S1", 币种="人民币", 单位="元")]
    B2 = [_记("b!B2", "S1", 币种="人民币", 单位="万元")]
    assert all(x["原因"] == "口径冲突" for x in 建立对应(A2, B2, _构(), _构()))


