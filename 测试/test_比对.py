def test_项标签不参与配对但仍进清单():
    A = [_记("a!B2", "", 角色="项标签", 序号=1, 行号=2),
         _记("a!C2", "S1", 序号=1, 行号=2)]
    B = [_记("b!B2", "", 角色="项标签", 序号=1, 行号=2),
         _记("b!C2", "S1", 序号=1, 行号=2)]
    清 = 建立对应(A, B, _构(), _构())
    assert any(x["a格"] == "a!B2" for x in 清)           # 项标签在清单里
    assert len([x for x in 清 if x["状态"] == "对应"]) == 1
